const isSequential = (digits: string) =>
  '01234567890'.includes(digits) || '09876543210'.includes(digits);

/** True when the password is easy to guess even though it is long enough. */
export function isWeakPassword(password: string, email = '', name = ''): boolean {
  const lower = password.trim().toLowerCase();
  // The text before trailing digits and symbols: «bybit2024!» → «bybit».
  const stem = lower.replace(/[^\p{L}]+$/u, '');
  if (COMMON.has(lower) || COMMON.has(stem)) return true;
  if (new Set(lower).size < 4) return true;
  if (/^\d+$/.test(lower) && isSequential(lower)) return true;
  const personal = [
    email.toLowerCase(),
    email.toLowerCase().split('@')[0] ?? '',
    name.toLowerCase(),
  ];
  return personal.some((p) => p.length >= 3 && (lower === p || stem === p));
}
